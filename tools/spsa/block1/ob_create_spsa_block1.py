def extract_spsa(form):
    # Same computation as OpenBench/workloads/create_workload.py:extract_spas_params()
    spsa = {}
    spsa['Alpha'  ] = float(form['spsa_alpha'])
    spsa['Gamma'  ] = float(form['spsa_gamma'])
    spsa['A_ratio'] = float(form['spsa_A_ratio'])
    spsa['iterations'] = int(form['spsa_iterations'])
    spsa['pairs_per' ] = int(form['spsa_pairs_per'])
    spsa['A'         ] = spsa['A_ratio'] * spsa['iterations']
    spsa['reporting_type'   ] = form['spsa_reporting_type']
    spsa['distribution_type'] = form['spsa_distribution_type']
    spsa['parameters'] = {}
    for index, line in enumerate(form['spsa_inputs'].split('\n')):
        name, data_type, value, minimum, maximum, c_end, r_end = line.split(',')
        assert data_type.strip() in ('int', 'float'), name
        assert float(minimum) <= float(value) <= float(maximum), name
        assert float(r_end) > 0, name
        param          = {}
        param['index'] = index
        param['float'] = data_type.strip() == 'float'
        param['start'] = float(value)
        param['value'] = float(value)
        param['min'  ] = float(minimum)
        param['max'  ] = float(maximum)
        param['c_end'] = float(c_end)
        param['r_end'] = float(r_end)
        param['c']     = param['c_end'] * spsa['iterations'] ** spsa['Gamma']
        param['a_end'] = param['r_end'] * param['c_end'] ** 2
        param['a']     = param['a_end'] * (spsa['A'] + spsa['iterations']) ** spsa['Alpha']
        spsa['parameters'][name] = param
    return spsa


def build_test(engine):
    f = FORM
    t = Test()
    t.author      = AUTHOR
    t.book_name   = f['book_name']
    t.upload_pgns = f['upload_pgns']
    t.dev = t.base = engine
    t.dev_repo         = t.base_repo         = f['dev_repo']
    t.dev_engine       = t.base_engine       = f['dev_engine']
    t.dev_options      = t.base_options      = f['dev_options']
    t.dev_network      = t.base_network      = f['dev_network']
    t.dev_time_control = t.base_time_control = OpenBench.utils.TimeControl.parse(f['dev_time_control'])
    t.variant_contract = OpenBench.variant_contract.configured_variant_contract(
        OPENBENCH_CONFIG, t.dev_engine, t.base_engine, t.book_name) or ''
    t.workload_size = int(f['spsa_pairs_per'])
    t.priority      = int(f['priority'])
    t.throughput    = int(f['throughput'])
    t.syzygy_wdl    = f['syzygy_wdl']
    t.syzygy_adj    = f['syzygy_adj']
    t.win_adj       = f['win_adj']
    t.draw_adj      = f['draw_adj']
    t.test_mode     = 'SPSA'
    t.spsa          = extract_spsa(f)
    t.awaiting      = False
    name = Network.objects.get(engine=t.dev_engine, sha256=t.dev_network).name
    t.dev_netname = t.base_netname = name
    return t


